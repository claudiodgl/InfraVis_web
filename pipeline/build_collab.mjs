// The collaboration network of the finale and the site, from the projects
// database (assets/data/projects_db.json: every project on infravis.se, with
// the nodes that took part, built 2026-11-27, see assets/data/README.md):
//   viewer/src/data/collab.js = { PROJECTS_DB, EDGES, NODE_COUNTS }
// An edge's weight = the projects in which both nodes took part (as an
// InfraVis node or as the users' home university); nodes only, no evidence
// fields, short titles — what the browser needs and nothing else.
// Run from the repo root:  node pipeline/build_collab.mjs
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import fs from 'node:fs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const db = JSON.parse(fs.readFileSync(path.join(root, 'assets', 'data', 'projects_db.json'), 'utf8'));
const NODE_IDS = new Set(db.nodes);

const short = (t) => t.replace(/\s*[:–—-]\s.*$/, '').replace(/^Visuali[sz](ing|ation of)\s+/i, '').slice(0, 48);
const projects = db.projects.map((p) => {
  const users = (p.users || []).filter((u) => NODE_IDS.has(u));
  const all = [...new Set([...p.nodes, ...users])];
  return { id: p.id, title: p.title, short: short(p.title), url: p.url, year: p.year, type: p.type,
    nodes: p.nodes, users, all, domain: p.domain, technique: p.technique, summary: p.summary, image: p.image || null };
});

// recount the edges from the data (the database's own list, checked)
const edges = new Map();
for (const p of projects) {
  const ns = [...p.all].sort();
  for (let i = 0; i < ns.length; i++) for (let j = i + 1; j < ns.length; j++) {
    const k = `${ns[i]}|${ns[j]}`;
    if (!edges.has(k)) edges.set(k, { a: ns[i], b: ns[j], weight: 0, projects: [] });
    const e = edges.get(k); e.weight++; e.projects.push(p.id);
  }
}
const EDGES = [...edges.values()].sort((x, y) => y.weight - x.weight);
const NODE_COUNTS = Object.fromEntries(db.nodes.map((n) => [n, projects.filter((p) => p.all.includes(n)).length]));

const out = `// generated by pipeline/build_collab.mjs from assets/data/projects_db.json
// (${db.source}, fetched ${db.fetched}) - do not edit by hand
export const PROJECTS_DB = ${JSON.stringify(projects)};
export const EDGES = ${JSON.stringify(EDGES)};
export const NODE_COUNTS = ${JSON.stringify(NODE_COUNTS)};
`;
fs.writeFileSync(path.join(root, 'viewer', 'src', 'data', 'collab.js'), out);
console.log(projects.length, 'projects,', EDGES.length, 'edges, max weight', EDGES[0].weight, '-', (out.length / 1024).toFixed(1), 'KB');
console.log(NODE_COUNTS);
