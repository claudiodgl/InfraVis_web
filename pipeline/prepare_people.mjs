// Portraits and partner logos for the browser:
//   assets/portraits/*  (15 MB of originals)  -> static/lib/portraits/<file>.webp,
//                        128 px square, centred on the face area (attention crop)
//   assets/portraits/people.json               -> viewer/src/data/people.js
//   assets/logos/partners/*.svg                -> static/lib/logos/partners/
// Run from the repo root:  node pipeline/prepare_people.mjs
import { createRequire } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';
import fs from 'node:fs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const req = createRequire(path.join(root, 'viewer', 'package.json'));
const sharp = (await import(pathToFileURL(req.resolve('sharp')).href)).default;

const SRC = path.join(root, 'assets', 'portraits');
const OUT = path.join(root, 'static', 'lib', 'portraits');
fs.mkdirSync(OUT, { recursive: true });
const people = JSON.parse(fs.readFileSync(path.join(SRC, 'people.json'), 'utf8'));

let bytes = 0;
const out = [];
for (const p of people) {
  const base = p.file.replace(/\.[^.]+$/, '');
  const dst = path.join(OUT, `${base}.webp`);
  try {
    await sharp(path.join(SRC, p.file), { animated: false })
      .resize(128, 128, { fit: 'cover', position: sharp.strategy.attention })
      .webp({ quality: 74 }).toFile(dst);
    bytes += fs.statSync(dst).size;
    out.push({ name: p.name, role: p.role, node: p.university_id, img: `./lib/portraits/${base}.webp`,
      groups: p.groups ?? [], profile: p.profile_url ?? null, affiliation: p.affiliation_text ?? null });
  } catch (e) { console.warn('skip', p.file, e.message); }
}
fs.writeFileSync(path.join(root, 'viewer', 'src', 'data', 'people.js'),
  `// generated by pipeline/prepare_people.mjs from assets/portraits/people.json\n// (infravis.se team and faculty pages, 2026-11-26) - do not edit by hand\nexport const PEOPLE = ${JSON.stringify(out, null, 1)};\n`);
console.log(out.length, 'portraits,', (bytes / 1024).toFixed(0), 'KB');

const LS = path.join(root, 'assets', 'logos', 'partners'), LO = path.join(root, 'static', 'lib', 'logos', 'partners');
fs.mkdirSync(LO, { recursive: true });
for (const f of fs.readdirSync(LS)) if (f.endsWith('.svg')) fs.copyFileSync(path.join(LS, f), path.join(LO, f));
console.log('logos:', fs.readdirSync(LO).map((f) => `${f} ${(fs.statSync(path.join(LO, f)).size / 1024).toFixed(0)}KB`).join(', '));
